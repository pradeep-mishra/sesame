private struct FileRecord: Equatable {
    let path: String
    let sha256: String
    let modified: TimeInterval
}

/// Every file under `folder`, as relative path, SHA-256 of its bytes and its modified time, sorted by path.
private func snapshot(of folder: URL) -> [FileRecord] {
    let fm = FileManager.default
    guard let walker = fm.enumerator(at: folder, includingPropertiesForKeys: [.isRegularFileKey, .contentModificationDateKey]) else { return [] }
    var out: [FileRecord] = []
    let prefix = folder.path + "/"
    for case let url as URL in walker {
        guard (try? url.resourceValues(forKeys: [.isRegularFileKey]))?.isRegularFile == true,
              let data = try? Data(contentsOf: url),
              let modified = (try? url.resourceValues(forKeys: [.contentModificationDateKey]))?.contentModificationDate else { continue }
        let digest = SHA256.hash(data: data).map { String(format: "%02x", $0) }.joined()
        let path = url.path
        out.append(FileRecord(path: path.hasPrefix(prefix) ? String(path.dropFirst(prefix.count)) : path,
                              sha256: digest, modified: modified.timeIntervalSince1970))
    }
    return out.sorted { $0.path < $1.path }
}

// MARK: running the helper

private final class Collector: @unchecked Sendable {
    private let lock = NSLock()
    private var data = Data()
    func add(_ chunk: Data) { lock.lock(); data.append(chunk); lock.unlock() }
    var text: String { lock.lock(); defer { lock.unlock() }; return String(decoding: data, as: UTF8.self) }
}

private final class PollState: @unchecked Sendable {
    private let lock = NSLock()
    private var stopped = false
    private var files: Set<String> = []
    private var peakMB = 0.0
    private var copied: [String: URL] = [:]
    var isStopped: Bool { lock.lock(); defer { lock.unlock() }; return stopped }
    func stop() { lock.lock(); stopped = true; lock.unlock() }
    func note(files seen: [String], peak: Double?, copies: [String: URL]) {
        lock.lock()
        files.formUnion(seen)
        if let peak { peakMB = max(peakMB, peak) }
        copied = copies
        lock.unlock()
    }
    var seenFiles: Set<String> { lock.lock(); defer { lock.unlock() }; return files }
    var peak: Double { lock.lock(); defer { lock.unlock() }; return peakMB }
    var copies: [String: URL] { lock.lock(); defer { lock.unlock() }; return copied }
}

private struct BenchRun {
    let status: Int32?          // nil when the helper had to be killed at the time limit
    let stdout: String
    let stderr: String
    let seconds: Double
    let pid: Int32
    let scratchFiles: Set<String>   // names seen under $TMPDIR/Sesame-<pid> while the helper ran
    let peakFootprintMB: Double
    let copies: [String: URL]       // relative path in the scratch folder -> the test's own copy of the biggest state seen
}

