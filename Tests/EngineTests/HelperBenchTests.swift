private final class SecondsBox: @unchecked Sendable {
    var value: Double?
}

/// The duration of an audio or movie file by AVFoundation, the test's own reader.
private func mediaSeconds(of url: URL) -> Double? {
    let box = SecondsBox()
    let done = DispatchSemaphore(value: 0)
    Task.detached {
        box.value = (try? await AVURLAsset(url: url).load(.duration))?.seconds
        done.signal()
    }
    _ = done.wait(timeout: .now() + 60)
    return box.value
}

