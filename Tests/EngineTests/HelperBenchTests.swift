private let codeExtensions: Set<String> = ["swift", "py", "js", "ts", "tsx", "jsx", "go", "rs", "java", "kt", "c", "h", "cpp", "rb", "sh"]

private let copiedExtensions: Set<String> = Set(["wav", "mp4", "pdf"]).union(codeExtensions)

/// Runs `SesameHelper index bench [model flags]` once, with nothing on stdin, `HOME` and `TMPDIR` in `world`, and
/// `SESAME_FAKE_EMBEDDER=1` only when `models` is nil. While it runs a poller lists `$TMPDIR/Sesame-<pid>`, copies every
/// wav, mp4 and pdf it finds there out to `world.seen` each time the file has grown, and reads the helper's lifetime peak footprint.
private func runBench(in world: BenchWorld, models: (text: URL, mm: URL)? = nil, timeout: TimeInterval = 300) throws -> BenchRun {
    let process = Process()
    process.executableURL = try releaseHelper()
    var arguments = ["index", "bench"]
    if let models { arguments += ["--text-model", models.text.path, "--mm-model", models.mm.path] }
    process.arguments = arguments
    var environment = ProcessInfo.processInfo.environment
    environment["HOME"] = world.home.path
    environment["TMPDIR"] = world.tmp.path + "/"
    environment.removeValue(forKey: "SESAME_FAKE_EMBEDDER")
    if models == nil { environment["SESAME_FAKE_EMBEDDER"] = "1" }
    process.environment = environment
    process.standardInput = FileHandle.nullDevice
    let outPipe = Pipe(), errPipe = Pipe()
    process.standardOutput = outPipe
    process.standardError = errPipe

    let out = Collector(), err = Collector()
    let readers = DispatchGroup()
    for (pipe, sink) in [(outPipe, out), (errPipe, err)] {
        readers.enter()
        Thread.detachNewThread {
            while true {
                let chunk = pipe.fileHandleForReading.availableData
                if chunk.isEmpty { break }
                sink.add(chunk)
            }
            readers.leave()
        }
    }
    let exited = DispatchSemaphore(value: 0)
    process.terminationHandler = { _ in exited.signal() }

    let started = Date()
    try process.run()
    let pid = process.processIdentifier
    let scratch = world.tmp.appendingPathComponent("Sesame-\(pid)", isDirectory: true)
    let seenFolder = world.seen.appendingPathComponent("run-\(pid)", isDirectory: true)
    try? FileManager.default.createDirectory(at: seenFolder, withIntermediateDirectories: true)

    let state = PollState()
    let polled = DispatchSemaphore(value: 0)
    Thread.detachNewThread {
        var lastFootprint = Date.distantPast
        var copySizes: [String: Int] = [:]
        var copyTargets: [String: URL] = [:]
        while !state.isStopped {
            var names: [String] = []
            if let walker = FileManager.default.enumerator(atPath: scratch.path) {
                for case let name as String in walker {
                    names.append((name as NSString).lastPathComponent)
                    let ext = (name as NSString).pathExtension.lowercased()
                    guard copiedExtensions.contains(ext) else { continue }
                    let full = scratch.appendingPathComponent(name)
                    guard let size = (try? FileManager.default.attributesOfItem(atPath: full.path))?[.size] as? Int,
                          size > (copySizes[name] ?? 0) else { continue }
                    let target = copyTargets[name] ?? seenFolder.appendingPathComponent("\(copyTargets.count)-" + (name as NSString).lastPathComponent)
                    try? FileManager.default.removeItem(at: target)
                    if (try? FileManager.default.copyItem(at: full, to: target)) != nil {
                        copySizes[name] = size
                        copyTargets[name] = target
                    }
                }
            }
            var peak: Double?
            if Date().timeIntervalSince(lastFootprint) > 0.1 {
                peak = Tools.footprintLifetimeMaxMB(pid: pid)
                lastFootprint = Date()
            }
            state.note(files: names, peak: peak, copies: copyTargets)
            Thread.sleep(forTimeInterval: 0.005)
        }
        polled.signal()
    }

    var status: Int32? = nil
    if exited.wait(timeout: .now() + timeout) == .success {
        status = process.terminationStatus
    } else {
        process.terminate()
        if exited.wait(timeout: .now() + 5) == .timedOut { kill(pid, SIGKILL); _ = exited.wait(timeout: .now() + 5) }
    }
    let seconds = Date().timeIntervalSince(started)
    state.stop()
    polled.wait()
    _ = readers.wait(timeout: .now() + 10)
    return BenchRun(status: status, stdout: out.text, stderr: String(err.text.prefix(400)), seconds: seconds, pid: pid,
                    scratchFiles: state.seenFiles, peakFootprintMB: state.peak, copies: state.copies)
}

/// Once per test process the helper binary does one bench run with generous time, so a cold Vision compile in that
/// binary is not mistaken for a stall by the tests. Nothing is asserted here.
private let benchWarm: Bool = {
    guard let world = try? BenchWorld() else { return false }
    defer { world.remove() }
    return (try? runBench(in: world, timeout: 300)) != nil
}()

private func withWorld(_ body: (BenchWorld) throws -> Void) throws {
    _ = benchWarm
    let world = try BenchWorld()
    defer { world.remove() }
    try body(world)
}

