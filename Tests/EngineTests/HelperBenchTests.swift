private let benchKinds = ["photo", "pdf", "doc", "audio", "video"]

/// Checks the run against the table row and returns the seconds per file of every kind, or nil when a check failed (the failures are recorded).
// plan-5-t8 amendment. Reason: plan 2 pinned `Set(speeds.keys) == ["photo"]` because only photos were measured; the entry of plan-5-t8 makes
// the bench measure every kind that is read, so the key set is the five kinds and each is a positive number. The photo bound (under 120 s) is
// unchanged; the new kinds get a loose sanity bound of 300 s (this file's pick: a 60 s clip or a 30 s video through the readers).
@discardableResult
private func expectOneBenchEvent(_ run: BenchRun, sourceLocation: SourceLocation = #_sourceLocation) -> [String: Double]? {
    let context = "after \(Int(run.seconds)) s, stdout \(String(run.stdout.prefix(300)).debugDescription), stderr \(run.stderr.debugDescription)"
    #expect(run.status == 0, "the helper must exit 0 by itself within the time allowed (status \(run.status.map(String.init) ?? "killed at the limit")); \(context)",
            sourceLocation: sourceLocation)
    let lines = run.stdout.split(separator: "\n", omittingEmptySubsequences: true)
    #expect(lines.count == 1, "stdout must be exactly one line, got \(lines.count); \(context)", sourceLocation: sourceLocation)
    #expect(run.stdout.hasSuffix("\n") && !run.stdout.hasSuffix("\n\n"), "the one line must end with exactly one newline; \(context)",
            sourceLocation: sourceLocation)
    guard lines.count == 1,
          let object = (try? JSONSerialization.jsonObject(with: Data(lines[0].utf8))) as? [String: Any] else {
        Issue.record("the line is not one JSON object: \(context)", sourceLocation: sourceLocation)
        return nil
    }
    #expect(object["event"] as? String == "bench", "event must be \"bench\"; \(context)", sourceLocation: sourceLocation)
    guard let speeds = object["speeds"] as? [String: Any] else {
        Issue.record("no `speeds` object: \(context)", sourceLocation: sourceLocation)
        return nil
    }
    #expect(Set(speeds.keys) == Set(benchKinds),
            "the key set of speeds is exactly photo, pdf, doc, audio, video; got \(speeds.keys.sorted())",
            sourceLocation: sourceLocation)
    var numbers: [String: Double] = [:]
    for kind in benchKinds {
        guard let number = speeds[kind] as? NSNumber, CFGetTypeID(number) != CFBooleanGetTypeID() else {
            Issue.record("speeds.\(kind) is missing or not a JSON number: \(context)", sourceLocation: sourceLocation)
            continue
        }
        let seconds = number.doubleValue
        let bound = kind == "photo" ? 120.0 : 300.0
        #expect(seconds > 0 && seconds < bound, "speeds.\(kind) must be above 0 and under \(Int(bound)) seconds per file, got \(seconds)",
                sourceLocation: sourceLocation)
        numbers[kind] = seconds
    }
    return numbers.count == benchKinds.count ? numbers : nil
}

private func imageLike(_ name: String) -> Bool {
    ["jpg", "jpeg", "png", "heic", "tif", "tiff", "gif", "bmp"].contains((name as NSString).pathExtension.lowercased())
}

private func textDocumentLike(_ name: String) -> Bool {
    ["txt", "md", "rtf", "html", "docx", "odt"].contains((name as NSString).pathExtension.lowercased())
}

private func hasExtension(_ name: String, _ wanted: String) -> Bool {
    (name as NSString).pathExtension.lowercased() == wanted
}

private func codeLike(_ name: String) -> Bool {
    codeExtensions.contains((name as NSString).pathExtension.lowercased())
}

